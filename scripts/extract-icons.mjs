// Copies the vector paths of the window's icons into the terminal mode, so both draw the
// same Phosphor icons. Run after changing the list: node scripts/extract-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";

const PHOSPHOR = "node_modules/phosphor-svelte/lib";
const OUTPUT = "src-tauri/src/tui/icon_paths.rs";

