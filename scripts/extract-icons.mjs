function phosphorPaths(component, weight) {
  const source = readFileSync(`${PHOSPHOR}/${component}.svelte`, "utf8");
  const branch = source.match(new RegExp(`weight === "${weight}"\\}\\s*([^{]*)`));
  if (!branch) throw new Error(`${component} has no ${weight} weight`);
  return [...branch[1].matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
}

function svgPaths(file) {
  return [...readFileSync(file, "utf8").matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
}

function playPausePaths(shape) {
  const source = readFileSync("src/lib/components/PlayPauseIcon.svelte", "utf8");
  const match = source.match(new RegExp(`${shape}: \\[([^\\]]+)\\]`));
  return [...match[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);
}

function constant(name, viewBox, paths) {
  const list = paths.map((d) => `"${d}"`).join(", ");
  return `pub const ${name}: Shape = Shape { view_box: ${viewBox.toFixed(1)}, paths: &[${list}] };\n`;
}

let output = `//! Generated by scripts/extract-icons.mjs from phosphor-svelte, simple-icons and
//! PlayPauseIcon.svelte. Do not edit by hand.

pub struct Shape {
    pub view_box: f32,
    pub paths: &'static [&'static str],
}

`;
for (const [name, component, weight] of ICONS) output += constant(name, 256, phosphorPaths(component, weight));
output += constant("PLAY", 24, playPausePaths("play"));
output += constant("PAUSE", 24, playPausePaths("pause"));
for (const [name, file] of [
  ["TELEGRAM", "telegram"],
  ["YOUTUBE_MUSIC", "youtubemusic"],
  ["SOUNDCLOUD", "soundcloud"],
  ["SPOTIFY", "spotify"],
]) {
  output += constant(name, 24, svgPaths(`node_modules/simple-icons/icons/${file}.svg`));
}

writeFileSync(OUTPUT, output);
console.log(`${ICONS.length + 6} icons written to ${OUTPUT}`);
